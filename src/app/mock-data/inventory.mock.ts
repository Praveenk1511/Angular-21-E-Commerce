/**
 * Inventory seed records: the single source of truth for stock.
 *
 * The catalogue holds no stock figures at all. Availability shown to a shopper is
 * computed by the mock API from `onHand - reserved`, combined with the product's
 * lifecycle. That is the whole reason inventory is a separate collection: two places
 * claiming to know how many units exist is how a shop oversells.
 *
 * Values are chosen to produce every stock state the UI needs:
 *
 * - healthy stock, well above the reorder level;
 * - low stock, at or under the reorder level;
 * - zero available because everything on hand is reserved;
 * - genuinely nothing on hand, with and without an inbound delivery.
 *
 * Products absent from this list are treated as having no stock record at all, which
 * the API reports as out of stock rather than silently assuming availability.
 */
export interface InventorySeed {
  readonly productId: string;
  readonly warehouseCode: string;
  readonly onHand: number;
  readonly reserved: number;
  readonly reorderLevel: number;
  readonly reorderQuantity: number;
  /** ISO 8601 of the last stock movement. */
  readonly updatedAt: string;
  /** ISO 8601 date of the next expected delivery, or `null`. */
  readonly incomingAt: string | null;
  readonly incomingQuantity: number;
}

